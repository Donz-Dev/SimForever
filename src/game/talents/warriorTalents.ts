import type { Talent, WarriorTreeId } from './Talent';

/**
 * The Warrior talent trees.
 *
 * Source: the World of Warcraft: Forever talent calculator,
 * https://www.wowhead.com/forever/talent-calc/warrior
 *
 * Read from that calculator's own grid rather than typed from a screenshot:
 * every row, column, rank maximum, tier requirement and prerequisite below came
 * out of the markup it renders, so the layout here is the layout it draws.
 *
 * NOTHING HERE HAS ANY EFFECT ON A SIMULATION. These are names, positions and
 * text. Spending a point changes what the interface shows and nothing else --
 * no damage number, no cooldown, no resource. Talents are the one thing on the
 * "data the project still needs" list that is now half-answered: the tree is
 * real, the effects are not implemented.
 *
 * TWO THINGS THIS SOURCE SETTLES, AND ONE IT BREAKS:
 *
 * 1. Mortal Strike, Bloodthirst and Shield Slam are 31-point capstones in three
 *    different trees. With 51 points a warrior can reach exactly one. The
 *    ability spreadsheet lists all three with no note of exclusivity, and
 *    `abilitiesForClass` currently hands out all three at once.
 * 2. Spearing Strike is an Arms talent, which is why it had no Classic
 *    counterpart to check against.
 * 3. CONFLICT: this calculator gives Mortal Strike "weapon damage plus 85".
 *    WoWForeverWarriorAbilities.xlsx gives it a base of 160. Both are Forever
 *    sources and they disagree. The abilities file still uses 160, because that
 *    is the sheet the ruleset owner supplied directly; this is flagged in
 *    docs/warrior-abilities.md and needs resolving.
 */

interface TalentRow {
  readonly row: number;
  readonly col: number;
  readonly ranks: number;
  readonly name: string;
  readonly icon: string;
  readonly tier: number;
  readonly requires?: string;
  readonly requiresRanks?: number;
  readonly description: string;
}

/** Turn a display name into the id used everywhere else. */
export function talentId(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '_');
}

