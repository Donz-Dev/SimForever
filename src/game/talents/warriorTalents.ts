function build(tree: WarriorTreeId, rows: readonly TalentRow[]): readonly Talent[] {
  return rows.map((row) => ({ ...row, tree, id: talentId(row.name) }));
}

export interface TalentTree {
  readonly id: WarriorTreeId;
  readonly name: string;
  /** Background art, matching the source calculator's own backdrop. */
  readonly accent: string;
  readonly talents: readonly Talent[];
}

