// ---- Class and form --------------------------------------------------------

/** Bear and Dire Bear Form: +50%, Forever's hotfix of Classic's +30%. */
export const BEAR_FORM_THREAT_MULTIPLIER = 1.5;
/** Cat Form's passive, -29%. */
export const CAT_FORM_THREAT_MULTIPLIER = 0.71;
/**
 * Every Rogue's class passive, -29%: the client row both Forever simulators
 * read. The owner briefly ruled 0.8 (round 47b) and then reverted it to 0.71
 * the same day -- so 0.71 is now a confirmed figure, not only a consensus one.
 */
export const ROGUE_THREAT_MULTIPLIER = 0.71;

export const BATTLE_STANCE_THREAT_MULTIPLIER = 0.8;
export const DEFENSIVE_STANCE_THREAT_MULTIPLIER = 1.3;
export const BERSERKER_STANCE_THREAT_MULTIPLIER = 0.8;

/** Righteous Fury: "Increases the threat generated by your Holy attacks by 90%." */
export const RIGHTEOUS_FURY_HOLY_THREAT_MULTIPLIER = 1.9;

/** Blessing of Salvation: "Reduces all threat generated ... by 30%." */
export const SALVATION_THREAT_MULTIPLIER = 0.7;

/** What a class and a form threaten for before anything else applies. */
export function classThreatModifiers(
  characterClass: ClassId,
  style: CombatStyleId,
): readonly ThreatModifier[] {
  const out: ThreatModifier[] = [];
  if (characterClass === 'rogue') out.push({ multiplier: ROGUE_THREAT_MULTIPLIER });
  if (style === 'bear') out.push({ multiplier: BEAR_FORM_THREAT_MULTIPLIER });
  if (style === 'cat') out.push({ multiplier: CAT_FORM_THREAT_MULTIPLIER });
  return out;
}

